# Shared helpers for run.sh. Every step here must be safe to run more than once.

info() { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33mwarning:\033[0m %s\n' "$*" >&2; }

# Detects the platform once. Sets OS to termux, arch, debian, fedora or gentoo.
# Debian covers Ubuntu and derivatives; fedora covers RHEL, Rocky and Alma.
# OS_ID keeps the exact distro (ubuntu, rocky, ...).
detect_os() {
    OS='' OS_ID=''
    if [ -n "${TERMUX_VERSION:-}" ] || [ -d /data/data/com.termux ]; then
        OS=termux OS_ID=termux
        return
    fi
    local like='' candidate
    if [ -r /etc/os-release ]; then
        OS_ID=$(. /etc/os-release && echo "${ID:-}")
        like=$(. /etc/os-release && echo "${ID_LIKE:-}")
    fi
    for candidate in $OS_ID $like; do
        case $candidate in
        arch) OS=arch ;;
        debian | ubuntu) OS=debian ;;
        fedora | rhel | centos) OS=fedora ;;
        gentoo) OS=gentoo ;;
        esac
        [ -n "$OS" ] && return
    done
    echo "Unsupported system: ${OS_ID:-unknown}" >&2
    exit 1
}

# Runs a command as root, using sudo only when needed (Termux and root shells have no sudo).
as_root() {
    if [ "$(id -u)" -eq 0 ] || [ "$OS" = termux ]; then
        "$@"
    else
        sudo "$@"
    fi
}

# want VAR "question": answers from $VAR (true/false) when set, otherwise asks.
# Without a terminal (Docker builds, CI) the answer defaults to no.
want() {
    local value=${!1:-} reply
    case $value in
    true | yes | y | 1) return 0 ;;
    false | no | n | 0) return 1 ;;
    esac
    [ -t 0 ] || return 1
    while read -rp "$2 (y/N) " reply; do
        case $reply in
        [yY]*) return 0 ;;
        [nN]* | '') return 1 ;;
        esac
    done
    return 1
}

# choose VAR "question" OPTION...: prints the chosen option. Reads $VAR when set;
# without a terminal it picks the last option.
choose() {
    local var=$1 question=$2 reply
    shift 2
    local options=("$@")
    if [ -n "${!var:-}" ]; then
        echo "${!var}"
        return
    fi
    if [ ! -t 0 ]; then
        echo "${options[-1]}"
        return
    fi
    PS3="$question "
    select reply in "${options[@]}"; do
        [ -n "$reply" ] && break
    done </dev/tty >&2
    echo "$reply"
}

# Downloads a URL to a file atomically, skipping it if the file already exists.
fetch_once() {
    local url=$1 dest=$2
    [ -s "$dest" ] && return 0
    mkdir -p "$(dirname "$dest")"
    curl -fsSL "$url" -o "$dest.part" && mv "$dest.part" "$dest"
}

# Latest stable release tag of a GitHub repo. Uses git instead of the REST API,
# which has a 60 requests/hour limit for anonymous users.
latest_tag() {
    git ls-remote --tags --refs "https://github.com/$1" |
        sed 's|.*refs/tags/||' |
        grep -E '^v?[0-9]+(\.[0-9]+)+$' |
        sort -V | tail -1
}

# github_binary OWNER/REPO BINARY ASSET...
# Installs the latest release build of a tool into ~/.local/bin, and updates it on
# later runs when a newer release exists. ASSET names the release archive, with
# {tag}, {version} (the tag without "v") and {arch} filled in; the first that
# exists is used.
github_binary() {
    local repo=$1 bin=$2 tag arch stamp tmp asset url=''
    shift 2
    arch=$(uname -m)
    case $arch in
    x86_64 | aarch64) ;;
    arm64) arch=aarch64 ;;
    *)
        warn "no prebuilt $bin for $arch, skipping"
        return 0
        ;;
    esac
    tag=$(latest_tag "$repo")
    if [ -z "$tag" ]; then
        warn "could not find the latest release of $repo"
        return 0
    fi
    stamp=~/.local/share/dotfiles/versions/$bin
    if [ -x ~/.local/bin/"$bin" ] && [ "$(cat "$stamp" 2>/dev/null)" = "$tag" ]; then
        return 0
    fi
    for asset in "$@"; do
        asset=${asset//\{tag\}/$tag}
        asset=${asset//\{version\}/${tag#v}}
        asset=${asset//\{arch\}/$arch}
        url="https://github.com/$repo/releases/download/$tag/$asset"
        curl -fsIL -o /dev/null "$url" && break
        url=''
    done
    if [ -z "$url" ]; then
        warn "no release asset of $repo $tag for $arch"
        return 0
    fi
    info "Installing $bin $tag from GitHub releases"
    tmp=$(mktemp -d)
    curl -fsSL "$url" | tar -xz -C "$tmp"
    mkdir -p ~/.local/bin "$(dirname "$stamp")"
    install -m 755 "$(find "$tmp" -type f -name "$bin" | head -1)" ~/.local/bin/"$bin"
    rm -rf "$tmp"
    echo "$tag" >"$stamp"
}

# Replaces ~/.zshrc with the concatenation of the given files. A .zshrc this
# script did not generate is backed up first, so nothing personal is lost.
write_zshrc() {
    local marker='# Generated by dotfiles/run.sh' tmp
    if [ -f ~/.zshrc ] && ! head -1 ~/.zshrc | grep -qF "$marker"; then
        local backup
        backup=~/.zshrc.backup-$(date +%Y%m%d%H%M%S)
        mv ~/.zshrc "$backup"
        warn "existing ~/.zshrc moved to $backup; put personal additions in ~/.zshrc.local"
    fi
    tmp=$(mktemp)
    {
        echo "$marker. Do not edit: changes are lost on the next run."
        echo '# Personal additions go in ~/.zshrc.local.'
        for part in "$@"; do
            echo
            cat "$part"
        done
    } >"$tmp"
    mv "$tmp" ~/.zshrc
}
